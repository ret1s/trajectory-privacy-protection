"""Render checked development scores; never select a winner on reporting data."""
import argparse
import json
from pathlib import Path

from experiments.run_contextual_lane import ROOT, CASES, METHODS, sha

LABELS = {'baseline': 'BR-làn gốc', 'route': 'Theo đường',
          'coverage': 'Theo POI', 'combined': 'Đường + POI'}


def render(payload):
    lines = ['% Generated by experiments.render_contextual_lane; do not edit scores.']
    for k in (3, 5):
        lines += [r'\begin{table}[H]\centering\small\setstretch{1.1}',
                  rf'\caption{{Phân tích thành phần trên họ phát triển 93, $K={k}$.',
                  r'Recall cao hơn có lợi cho ứng dụng; Hit thấp hơn và MAE cao hơn có lợi cho riêng tư.',
                  r'Hit/MAE là kiểm tra thăm dò giữa các đối thủ, không phải phép thử giữ kín.}',
                  rf'\label{{tab:context-k{k}}}',
                  r'\begin{tabularx}{\textwidth}{P{1.0cm}Yrrr}\toprule',
                  r'Ca & Biến thể & Recall@5 (\%) & Hit$_{100}$ (\%) & MAE (m)\\\midrule']
        for case in CASES:
            for i, name in enumerate(METHODS):
                s = next(s for s in payload['summaries']
                         if (s['split'], s['k'], s['case_id'], s['method']) ==
                         ('development_test', k, case, name))
                lines.append(f"{case if i == 0 else ''} & {LABELS[name]} & "
                             f"{100*s['poi_recall']:.2f} & {100*s['audit_max_hit100']:.2f} & "
                             f"{s['audit_min_mae_m']:.1f}" + r'\\')
            if case != CASES[-1]:
                lines.append(r'\midrule')
        lines += [r'\bottomrule\end{tabularx}', r'\end{table}']
    return '\n'.join(lines) + '\n'


def main(directory, check=False):
    directory = Path(directory)
    source = directory/'results.json'
    assert sha(source) == source.with_suffix('.sha256').read_text().strip()
    text = render(json.loads(source.read_text()))
    target = directory/'results_tables.tex'
    if check:
        assert target.read_text() == text, 'Stale or manually edited thesis tables'
        print(f'Verified all 40 displayed rows: {sha(target)}')
    else:
        target.write_text(text)
        print(target)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--directory', type=Path, default=ROOT/'artifacts/benchmarks/contextual_lane')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    main(args.directory, args.check)
