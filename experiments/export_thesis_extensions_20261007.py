"""Format additional source-backed thesis evidence; never generate scores.

Kept separate from the retained October6 exporter and evidence snapshots.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'thesis/current_extensions_generated'
S8 = 'artifacts/benchmarks/s8_companion_inference_20261007_v1/'
SENSOR = 'artifacts/benchmarks/local_gps_robustness_20261007_v1/'
SOURCES = {'resource': 'artifacts/benchmarks/public_resource_footprint_20261007_v1/readout.json',
           's8_protocol': S8 + 'protocol.json', 's8_readout': S8 + 'readout.json',
           's8_validation': S8 + 'validation.json', 's8_verification': S8 + 'verification_protocol.json',
           'sensor_protocol': SENSOR + 'protocol.json', 'sensor_readout': SENSOR + 'readout.json',
           'sensor_validation': SENSOR + 'validation.json', 'sensor_verification': SENSOR + 'verification_protocol.json',
           'sensor_baseline': SENSOR + 'baseline_recovery.json'}


def sha(path): return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def vn(value, digits=2): return f'{value:.{digits}f}'.replace('.', ',')


def integer(value): return f'{value:,}'.replace(',', r'\,')


def render():
    sources = {name: json.loads((ROOT / path).read_text()) for name, path in SOURCES.items()}
    resource = sources['resource']
    for path, pin in resource['source_sha256'].items(): assert sha(ROOT / path) == pin, path
    sig = resource['arrays']['signatures']
    n, categories, L = sig['shape']
    assert n * categories * L * sig['itemsize'] == sig['payload_bytes']
    rows = [('NPZ L60 trên đĩa', resource['archive_bytes_on_disk']),
            ('Signature L60 khi mở', sig['payload_bytes']),
            ('Mảng access', resource['arrays']['access']['payload_bytes']),
            ('Prefix signature L10 nếu materialize', resource['signature_prefix_storage_if_materialized']['10']),
            ('Cache 256 vector float64 nếu đầy', resource['distance_cache_storage_if_full_float64']['ranking_default_256_entries']),
            ('Cache offline 4.096 vector nếu đầy', resource['distance_cache_storage_if_full_float64']['offline_evaluator_4096_entries'])]
    prefix = '% Generated by experiments/export_thesis_extensions_20261007.py; do not hand-edit.\n'
    outputs = {'resource_rows.tex': prefix + '\\newcommand{\\EvalResourceRows}{%\n' + '\n'.join(
        label + ' & ' + integer(value) + ' & ' + vn(value / 1e6) + r' \\' for label, value in rows) + '\n}\n'}
    s8, cert = sources['s8_readout'], sources['s8_validation']
    assert cert['status'] == 'pass' and cert['test_families'] == 3 and cert['pairs'] == 22
    assert cert['protocol_sha256'] == sha(ROOT / SOURCES['s8_protocol'])
    assert cert['readout_sha256'] == sha(ROOT / SOURCES['s8_readout'])
    assert cert['verification_protocol_sha256'] == sha(ROOT / SOURCES['s8_verification'])
    for path, pin in sources['s8_protocol']['source_sha256'].items(): assert sha(ROOT / path) == pin, path
    attacker_labels = {'public_target_last': 'Tâm Q cuối', 'public_partner_velocity': 'Ngoại suy đồng hành'}
    rows = []
    for view, label in [('target_only', 'Chỉ mục tiêu'),
                        ('joint_protected_partner', 'Thêm đồng hành đã bảo vệ'),
                        ('joint_public_raw_partner', 'Thêm GPS đồng hành công khai'),
                        ('joint_unrelated_protected_partner', 'Thêm người khác, đã bảo vệ'),
                        ('raw_target_positive_control', 'GPS mục tiêu công khai')]:
        result = s8['results'][view]; metric = result['test']; attacker = result['selected_attacker']
        name = 'Vị trí Raw cuối' if view == 'raw_target_positive_control' else attacker_labels[attacker]
        rows.append(label + r' & \textbf{' + name + '} & ' + vn(metric['family_macro_mae_m'], 1)
                    + ' & ' + vn(100 * metric['family_macro_hit100']) + r' \\')
    outputs['s8_rows.tex'] = prefix + '\\newcommand{\\EvalSCompanionRows}{%\n' + '\n'.join(rows) + '\n}\n'
    sensor, cert = sources['sensor_readout'], sources['sensor_validation']
    assert cert['status'] == 'pass' and cert['blocks'] == 72
    assert cert['test_family_clusters'] == 24 and cert['nested_draws'] == 3
    assert cert['protocol_sha256'] == sha(ROOT / SOURCES['sensor_protocol'])
    assert cert['readout_sha256'] == sha(ROOT / SOURCES['sensor_readout'])
    assert cert['verification_protocol_sha256'] == sha(ROOT / SOURCES['sensor_verification'])
    assert cert['verifier_sha256'] == sha(ROOT / 'experiments/verify_local_gps_robustness_20261007.py')
    for path, pin in sources['sensor_protocol']['source_sha256'].items(): assert sha(ROOT / path) == pin, path
    for key in ('fixed_Q_clocks_anchors_ledger_wire', 'no_private_key_or_protection_sampler_calls',
                'source_already_inspected_secondary_only', 'all_exact_current_scores_recovered'):
        assert sensor[key] is True, key
    assert sources['sensor_baseline']['all_exact_current_scores_recovered'] is True
    assert sensor['baseline_recovery_sha256'] == sha(ROOT / SOURCES['sensor_baseline'])
    assert cert['public_events'] == sensor['total_public_events'] == 18114
    assert cert['local_virtual_fixes'] == sensor['virtual_local_sensor_fixes'] == 6336
    variants = [('exact_event_oracle', 'GPS chính xác mỗi event')]
    variants += [(f'hold_last60_s{s}', r'Giữ fix, $\sigma=' + str(s) + r'$ m') for s in (0, 5, 15)]
    variants += [(f'velocity_twofix60_s{s}', r'Ngoại suy, $\sigma=' + str(s) + r'$ m') for s in (0, 5, 15)]
    main_rows, three_rows, safety_rows, gains = [], [], [], []
    for variant, label in variants:
        error = sensor['position_error'][variant]
        assert error['events'] == 18114 and error['invalid_events'] == 0
        before, after = [sensor['summary'][variant + '--L' + str(depth)]['all'] for depth in (20, 30)]
        values = [100 * value['equal_purpose_macro']['family_mean'] for value in (before, after)]
        main_rows.append(label + ' & ' + vn(error['error_before_snap_m']['mean'], 1) + ' & '
                         + vn(error['error_after_snap_m']['mean'], 1) + ' & ' + vn(values[0]) + ' & ' + vn(values[1]) + r' \\')
        three_rows.append(label + ' & ' + ' & '.join(vn(100 * value['three_purpose_macro']['family_mean'])
                                                   for value in (before, after)) + r' \\')
        radius = after['within_radius']; counts = radius['explicit_denominators']
        assert counts['reference_category_count'] == 42258 and counts['defined_events'] == 17577
        safety_rows.append(label + ' & ' + vn(100 * radius['family_mean']) + ' & '
                           + integer(counts['returned_outside_true_domain']) + '/' + integer(counts['returned_items'])
                           + ' & ' + integer(counts['zero_answer_reference_categories']) + '/' + integer(counts['reference_category_count']) + r' \\')
        for depth in (20, 30):
            assert sensor['cost'][variant + '--L' + str(depth)] == sensor['cost']['exact_event_oracle--L' + str(depth)]
        if variant != 'exact_event_oracle': gains.append(values[1] - values[0])
    content = prefix
    for name, rows in [('SensorRowsSeven', main_rows), ('SensorThreePurposeRows', three_rows), ('SensorSafetyRows', safety_rows)]:
        content += '\\newcommand{\\' + name + '}{%\n' + '\n'.join(rows) + '\n}\n'
    for name, value in [('SensorEvents', integer(cert['public_events'])), ('SensorVirtualFixes', integer(cert['local_virtual_fixes'])),
                        ('SensorFamilyCount', '24'), ('SensorDrawCount', '3'), ('SensorMinNonOracleGain', vn(min(gains))),
                        ('SensorMaxNonOracleGain', vn(max(gains)))]:
        content += '\\newcommand{\\' + name + '}{' + value + '}\n'
    outputs['sensor_rows.tex'] = content
    manifest = {'schema': 'thesis-extensions-evidence-export-v1', 'as_of': '2026-10-07',
                'exporter_sha256': sha(__file__),
                'source_sha256': {p: sha(ROOT / p) for p in SOURCES.values()},
                'generated_sha256': {name: hashlib.sha256(value.encode()).hexdigest() for name, value in outputs.items()},
                'scope': 'Formatting retained evidence only; no model fit, selection, score or bootstrap regeneration.'}
    outputs['sources.json'] = json.dumps(manifest, indent=2, ensure_ascii=False, allow_nan=False) + '\n'
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__); parser.add_argument('--check', action='store_true')
    args = parser.parse_args(); outputs = render()
    if args.check:
        for name, content in outputs.items(): assert (OUT / name).read_text() == content, name
        print(f'PASS: {len(SOURCES)} source readouts, {len(outputs)-1} deterministic TeX fragments')
    else:
        OUT.mkdir(parents=True, exist_ok=True)
        for name, content in outputs.items(): (OUT / name).write_text(content)
        print(f'Exported {len(outputs)-1} TeX fragments')


if __name__ == '__main__': main()
