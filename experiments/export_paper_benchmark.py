"""Export thesis tables only after verifying source and metric consistency."""
from collections import Counter
import json
from pathlib import Path
import numpy as np
from experiments.verify_paper_benchmark import DEFAULT, verify

NAMES = {'unprotected': 'Không bảo vệ', 'uniform_dummy': 'Dummy đều',
         'dls_graph_adaptation': 'DLS thích nghi', 'rem_anchor_only': 'Chỉ neo REM',
         'transprotect_adaptation': 'TransProtect thích nghi', 'anotherme_adaptation': 'AnotherMe thích nghi',
         'semantic_correlation_local_adaptation': 'Semantic thích nghi',
         'geo_i_anchored_dummy': 'Neo--dummy hình học', 'geo_i_anchored_dummy_road': 'Neo--dummy đường cũ',
         'br_fresh': 'BR neo mới', 'br_private': 'BR tái sử dụng', 'br_selected': 'BR chọn trên tập riêng'}


def fmt(x, pct=False):
    return '--' if x is None else f'{x * (100 if pct else 1):.1f}'


def main():
    audit = verify()
    data = json.loads(DEFAULT.read_text())
    lookup = {(s['scenario'], s['method'], s['k']): s for s in data['summary']}
    def s(case, method, k=3):
        return lookup[case, method, k]
    counts = Counter(r['status'] for r in data['rows'])
    text = [r'% Auto-generated by experiments.export_paper_benchmark; do not hand-edit numbers.',
            f"Bộ kiểm thử gồm {len(data['dataset_records'])} đoạn thuộc 12 chuyến mô phỏng phân biệt theo cặp seed/xe, "
            f"năm kịch bản, hai mức $K$ và 12 cấu hình báo cáo. Trong {len(data['rows'])} lượt, "
            f"{counts['ok']} hoàn tất, {counts['not_applicable']} không áp dụng và {counts['failed']} lỗi thực thi. "
            r"AnotherMe không áp dụng S1/S2/S9/S10; một lượt S3 không tìm được điểm ảo cuối phân biệt có thể tới. Không bỏ lỗi khỏi mẫu số tác vụ.",
            r'\subsection{Vị trí đơn lẻ, điểm dừng và đoạn di chuyển}']
    for case, title in [('S1', 'một lần gửi'), ('S2', 'tích luỹ tại điểm dừng'), ('S3', 'tái dựng đoạn di chuyển')]:
        text += [r'\begingroup\small\setstretch{1.05}', r'\begin{longtable}{p{4.3cm}rrrrr}',
                 f'\\caption{{{case}: {title}, $K=3$. MAE theo mét; Hit và Recall theo phần trăm.}}\\\\',
                 r'\toprule Phương pháp & Chạy & MAE $\uparrow$ & SD & Hit$_{100}\downarrow$ & Recall $\uparrow$\\\midrule\endfirsthead',
                 r'\toprule Phương pháp & Chạy & MAE $\uparrow$ & SD & Hit$_{100}\downarrow$ & Recall $\uparrow$\\\midrule\endhead']
        for method, name in NAMES.items():
            row = s(case, method)
            completion = 'N/A' if row['not_applicable'] == row['attempted'] else f"{row['completed']}/{row['attempted']}"
            text.append(' & '.join([name, completion, fmt(row['location_mae_m']), fmt(row['location_mae_sd_m']), fmt(row['location_hit_100m'], True), fmt(row['poi_delivered_recall_at_k'], True)]) + r'\\')
        text += [r'\bottomrule\end{longtable}\endgroup']
    fresh, reuse = s('S2', 'br_fresh'), s('S2', 'br_private')
    text.append(f"Ở S2/$K=3$, BR tái sử dụng có Hit$_{{100}}$ {fmt(reuse['location_hit_100m'], True)}\\% so với {fmt(fresh['location_hit_100m'], True)}\\% của BR neo mới; Recall tương ứng {fmt(reuse['poi_delivered_recall_at_k'], True)}\\% và {fmt(fresh['poi_delivered_recall_at_k'], True)}\\%. Đây là tín hiệu trên 12 chuyến, chưa là kiểm định có ý nghĩa thống kê. Cấu hình được chọn chung mọi kịch bản cũng không nhất thiết tốt hơn bản cố định ở từng kịch bản.")
    old, fresh = s('S3', 'geo_i_anchored_dummy_road'), s('S3', 'br_fresh')
    text.append(f"Ở S3/$K=3$, BR neo mới có Recall {fmt(fresh['poi_delivered_recall_at_k'], True)}\\% so với {fmt(old['poi_delivered_recall_at_k'], True)}\\% của bản đường cũ; cả hai đạt 100\\% chuyển tiếp theo đồ thị nút. Thay đổi gồm miền liên thông mạnh, miền tới được và cách đặt độ lệch, nên không quy toàn bộ cải thiện cho duy nhất một thành phần. Tính đúng đồ thị không tự chứng minh riêng tư hoặc đạt đủ ràng buộc SUMO.")
    text.append(f"Mốc không bảo vệ chỉ đạt {fmt(s('S3', 'unprotected')['directed_track_validity'], True)}\\% chuyển tiếp hợp lệ theo phép đo nút ở S3/$K=3$. Chiếu từ vị trí dọc cạnh sang nút gần nhất có thể tạo bước nhảy không tương ứng chuyển động vật lý; không được kết luận xe SUMO đi sai luật. Đây cũng là yếu tố có thể làm cơ chế ràng buộc đường bị trễ và giảm chất lượng: cần chuyển sang trạng thái cạnh/làn để xác nhận lại đánh đổi.")
    text.append(r'S2 cho thấy dummy chứa thật có thể bị giao tập qua các lần gửi: DLS và dummy đều vẫn có Hit$_{100}$ rất cao dù một lần gửi có thể gây sai số lớn. Các bộ suy luận gần đúng còn có thể kém ở S1; MAE lớn không chứng minh đã chống đối thủ tối ưu.')
    text += [r'\subsection{Che biên hành trình không đồng nghĩa bảo vệ toàn bộ endpoint}',
             r'\begin{table}[htbp]\centering\small',
             r'\caption{Điểm biên bị che, $K=3$; 12 endpoint mỗi kịch bản/phương pháp.}',
             r'\begin{tabular}{lrrrr}\toprule & \multicolumn{2}{c}{S9: điểm đầu} & \multicolumn{2}{c}{S10: điểm cuối}\\',
             r'Phương pháp & MAE (m) & Hit$_{100}$ (\%) & MAE (m) & Hit$_{100}$ (\%)\\\midrule']
    for method in NAMES:
        if method == 'anotherme_adaptation':
            continue
        a, b = s('S9', method), s('S10', method)
        text.append(' & '.join([NAMES[method], fmt(a['location_mae_m']), fmt(a['location_hit_100m'], True), fmt(b['location_mae_m']), fmt(b['location_hit_100m'], True)]) + r'\\')
    text += [r'\bottomrule\end{tabular}\end{table}',
             r'Ngay mốc không bảo vệ cũng không cung cấp endpoint đã bị che: nó công bố chính xác phần cửa sổ còn thấy. Vì vậy sai số ở đây bao gồm khó khăn do chính sách che và giới hạn đối thủ. Hit bằng 0 trên 12 chuyến không có nghĩa xác suất tấn công trong quần thể bằng 0. Không trộn MAE endpoint với MAE các vị trí quan sát để tạo một bảng xếp hạng duy nhất.',
             r'\subsection{Chọn tham số và độ nhạy theo số dummy}',
             r'\begin{table}[htbp]\centering\small',
             r'\caption{Cấu hình chọn trên tập riêng; Recall tối thiểu tính trên năm kịch bản.}',
             r'\begin{tabular}{rrrrrr}\toprule Seed & $K$ & $\theta$ (m) & Độ lệch (m) & Min Recall (\%) & Đạt 90\%?\\\midrule']
    for m in data['manifests']:
        for choice in m['defender_selection']:
            spec = choice['selected']
            candidate = next(o for o in choice['candidates'] if o['spec'] == spec)
            text.append(f"{m['seed']} & {choice['k']} & {spec['theta_m']:.0f} & {spec['offset_m']:.0f} & {fmt(candidate['min_case_recall'], True)} & {'Có' if choice['utility_feasible'] else 'Không'}" + r'\\')
    text += [r'\bottomrule\end{tabular}\end{table}',
             r'Không cấu hình nào trong lưới đạt ràng buộc chất lượng ở cả năm kịch bản trên tập chọn cơ chế. Do đó bản được chọn là phương án dự phòng theo quy tắc đã khai báo, không phải nghiệm đạt mục tiêu. Kết quả âm này giới hạn trực tiếp mức độ hoàn thiện của thuật toán.',
             r'\begingroup\small\setstretch{1.05}\begin{longtable}{llrrrr}',
             r'\caption{Đối chiếu BR: Hit$_{100}$ và Recall theo phần trăm.}\\',
             r'\toprule Case & Biến thể & Hit $K=3$ & Recall $K=3$ & Hit $K=5$ & Recall $K=5$\\\midrule\endfirsthead',
             r'\toprule Case & Biến thể & Hit $K=3$ & Recall $K=3$ & Hit $K=5$ & Recall $K=5$\\\midrule\endhead']
    for case in ['S1', 'S2', 'S3', 'S9', 'S10']:
        for method in ['br_fresh', 'br_private', 'br_selected']:
            a, b = s(case, method, 3), s(case, method, 5)
            text.append(' & '.join([case, NAMES[method], fmt(a['location_hit_100m'], True), fmt(a['poi_delivered_recall_at_k'], True), fmt(b['location_hit_100m'], True), fmt(b['poi_delivered_recall_at_k'], True)]) + r'\\')
    text += [r'\bottomrule\end{longtable}\endgroup',
             r'\subsection{Chất lượng bổ sung, chi phí và kiểm chứng}',
             r'\begin{table}[htbp]\centering\small',
             r'\caption{S3/$K=3$: trả đủ, khoảng cách đi thêm có điều kiện và chi phí.}',
             r'\begin{tabular}{lrrrr}\toprule Biến thể & Trả đủ (\%) & Thêm (m) & JSON (byte) & Sinh (ms/sự kiện)\\\midrule']
    for method in ['geo_i_anchored_dummy_road', 'br_fresh', 'br_private', 'br_selected']:
        row = s('S3', method)
        text.append(' & '.join([NAMES[method], fmt(row['poi_complete_rate'], True), fmt(row['poi_extra_distance_m']), fmt(row['payload_json_bytes_per_request']), fmt(row['amortized_generation_ms'])]) + r'\\')
    text += [r'\bottomrule\end{tabular}\end{table}']
    br = [r for r in data['rows'] if r['method'] == 'br_selected' and r['status'] == 'ok']
    p95 = np.mean([r['metrics']['generation_p95_ms'] for r in br])
    text.append(f"Trung bình các p95 từng đoạn của BR được chọn là {p95:.2f} ms/sự kiện trên máy phát triển; đây không phải p95 gộp toàn bộ sự kiện, độ trễ mạng hay số đo trên điện thoại. Dung lượng JSON gồm sáu loại POI; ràng buộc đường được kiểm tra ở trạng thái nút, chưa ở cạnh/làn.")
    text.append(f"Kiểm tra tiền tố có {audit['prefix_pass']}/{audit['prefix_total']} trường hợp giống nhau. Sáu trường hợp không giống thuộc AnotherMe dùng cả đoạn; các cơ chế có giao diện trực tuyến vượt qua kiểm tra đã chạy. Sổ BR không vượt $B$; tọa độ thật và endpoint được giữ ngoài bản tin đối thủ. Các giá trị, lựa chọn và dữ liệu nguồn được lưu để tính lại, không lấy ảnh demo làm bằng chứng tính đúng.")
    (DEFAULT.parent / 'results_tables.tex').write_text('\n\n'.join(text) + '\n')
    print(json.dumps(audit, indent=2))


if __name__ == '__main__':
    main()
