"""Exact-lookup thesis tables from independently verified, immutable scores."""
import argparse
import json
from pathlib import Path

import numpy as np

from experiments.run_belief_suite import OUTPUT, METHODS, CASES
from experiments.run_contextual_lane import sha

LABELS={'baseline':'BR-làn gốc','point6':'POI tại neo',
        'belief6':'Phân bố 6','belief24':'Phân bố 24','belief24_center':'Phân bố 24 + tâm'}


def aggregate(payload):
    out=[]
    for k in (3,5):
        for name in METHODS:
            s=[s for s in payload['summaries'] if (s['k'],s['method'])==(k,name)]
            assert len(s)==9
            rows=[r for r in payload['rows'] if (r['k'],r['method'])==(k,name)]
            steps=[ms for r in rows for ms in r['step_ms']]
            out.append({'method':name,'k':k,'macro_recall':float(np.mean([x['poi_recall'] for x in s])),
                'min_recall':min(x['poi_recall'] for x in s),
                'macro_complete':float(np.mean([x['poi_complete'] for x in s])),
                'macro_selected_hit100':float(np.mean([x['selected_hit100'] for x in s])),
                'macro_envelope_hit100':float(np.mean([x['audit_max_hit100'] for x in s])),
                'macro_selected_mae_m':float(np.mean([x['selected_mae_m'] for x in s])),
                'step_median_ms':float(np.median(steps)),'step_p95_ms':float(np.percentile(steps,95))})
    return out


def render(payload,selection):
    lines=['% Generated by experiments.render_belief_suite; do not edit scores.']
    macro=aggregate(payload)
    for k in (3,5):
        lines += [r'\begin{table}[H]\centering\small\setstretch{1.08}',
            rf'\caption{{Kết quả xác nhận trên nhóm 105/106, $K={k}$: trung bình đều chín ca.',
            r'$R$: Recall@5; $R_{\min}$: Recall của ca yếu nhất; $H$: Hit$_{100}$ của đối thủ chọn bằng validation;',
            r'$H^*$: bao trên thăm dò giữa các đối thủ; $E$: MAE của đối thủ chọn bằng validation.',
            r'$R,R_{\min},H,H^*$ theo \%; $E$ theo mét.}',
            rf'\label{{tab:belief-grid-{k}}}',
            r'\begin{tabularx}{\textwidth}{Yrrrrr}\toprule',
            r'Biến thể & $R\uparrow$ & $R_{\min}\uparrow$ & $H\downarrow$ & $H^*\downarrow$ & $E\uparrow$\\\midrule']
        for name in METHODS:
            r=next(x for x in macro if (x['k'],x['method'])==(k,name))
            values=[r[f] for f in ('macro_recall','min_recall','macro_selected_hit100','macro_envelope_hit100')]
            lines.append(LABELS[name]+' & '+' & '.join(f'{100*v:.2f}' for v in values)+f' & {r["macro_selected_mae_m"]:.1f}'+r'\\')
        lines += [r'\bottomrule\end{tabularx}\end{table}']
    lines.append(r'\clearpage')
    for k in (3,5):
        chosen=selection['method_selection'][str(k)]['chosen']['method']
        lines += [r'\begin{table}[H]\centering\small\setstretch{1.08}',
            rf'\caption{{Đối chiếu từng ca trên nhóm 105/106, $K={k}$: BR-làn gốc và {LABELS[chosen]}.',
            r'$R$ là Recall@5 (\%); $H$ là Hit$_{100}$ (\%) với đối thủ được cố định trên validation, riêng cho từng cơ chế và ca.}',
            rf'\label{{tab:belief-cases-{k}}}',
            r'\begin{tabularx}{\textwidth}{Yrrrr}\toprule',
            r'Ca & $R$ gốc & $R$ cấu hình chọn & $H$ gốc & $H$ cấu hình chọn\\\midrule']
        for case in CASES:
            b=next(s for s in payload['summaries'] if (s['method'],s['k'],s['case_id'])==('baseline',k,case))
            c=next(s for s in payload['summaries'] if (s['method'],s['k'],s['case_id'])==(chosen,k,case))
            values=[b['poi_recall'],c['poi_recall'],b['selected_hit100'],c['selected_hit100']]
            lines.append(case+' & '+' & '.join(f'{100*v:.2f}' for v in values)+r'\\')
        lines += [r'\bottomrule\end{tabularx}\end{table}']
    return '\n'.join(lines)+'\n',macro


def main(directory,check=False):
    directory=Path(directory)
    p=json.loads((directory/'confirmation.json').read_text())
    selected=json.loads((directory/'selection.json').read_text())
    v=json.loads((directory/'verification.json').read_text())
    assert v['verified'] and v['replay'] and v['confirmation_sha256']==sha(directory/'confirmation.json')
    assert v['selection_sha256']==sha(directory/'selection.json')
    text,macro=render(p,selected)
    target=directory/'results_tables.tex'; aggregate_path=directory/'aggregate.json'
    if check:
        assert target.read_text()==text and json.loads(aggregate_path.read_text())==macro
    else:
        target.write_text(text)
        aggregate_path.write_text(json.dumps(macro,indent=2)+'\n')
    print(f'Tables and aggregate checked: {sha(target)}')


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--directory',type=Path,default=OUTPUT)
    p.add_argument('--check',action='store_true')
    a=p.parse_args(); main(a.directory,a.check)
