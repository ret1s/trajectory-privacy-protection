"""Exploratory attack-envelope tables, separate from validation-selected scores.

One attacker per metric/group is chosen over reporting rows ONLY as a
developmental vulnerability audit. This is not held-out attacker selection.
"""
import argparse
import hashlib
import json
from pathlib import Path

import numpy as np

from experiments.run_lane_comparison import ROOT, METHODS, CASES

LABELS={'unprotected':'Không bảo vệ','uniform_sets':'Tập dummy đều','dls':'DLS',
        'enhanced_dls':'Enhanced-DLS','lane_br_projected':'BR-làn, đầu vào nút',
        'lane_br_raw':'BR-làn, GPS gốc'}


def summarize(path):
    path=Path(path)
    p=json.loads(path.read_text())
    rows=[]
    for s in p['summaries']:
        group=[r for r in p['rows'] if (r['method'],r['k'],r['case_id'],r['split'])==
               (s['method'],s['k'],s['case_id'],'development_test')]
        maes={a:float(np.mean([np.mean(r['errors_by_attack'][a]) for r in group])) for a in group[0]['errors_by_attack']}
        hits={a:float(np.mean([np.mean(np.array(r['errors_by_attack'][a])<=100) for r in group])) for a in maes}
        rows.append({**s,'audit_min_mae_m':min(maes.values()),'audit_max_hit100':max(hits.values()),
                     'audit_mae_attack':min(maes,key=lambda a:(maes[a],a)),
                     'audit_hit_attack':max(hits,key=lambda a:(hits[a],a))})
    projection={key:{'n':len(values),'mean_m':float(np.mean(values)),
                     'p95_m':float(np.percentile(values,95)),'max_m':float(max(values))}
                for key in ('nearest_lane_error_m','nearest_junction_error_m')
                for values in [[v for r in p['records'] for v in r[key]]]}
    audit={'interpretation':'exploratory_report_family_attack_envelope_NOT_held_out_selection',
           'source_sha256':hashlib.sha256(path.read_bytes()).hexdigest(),
           'summarizer_sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
           'projection':projection,'rows':rows}
    (path.parent/'audit.json').write_text(json.dumps(audit,ensure_ascii=False,indent=2)+'\n')
    tex=['% Generated by experiments.summarize_lane_comparison; do not edit scores.']
    for k in (3,5):
        tex += [r'\begin{table}[htbp]\centering\small',
                r'\caption{Kiểm tra khả năng tấn công trên ba ca phát triển, $K='+str(k)+r'$.',
                r'MAE nhỏ nhất và Hit lớn nhất trong các đối thủ đã định nghĩa; không là đánh giá giữ kín độc lập.}',
                r'\label{tab:lane-k'+str(k)+'}',
                r'\begin{tabularx}{\textwidth}{YP{1.25cm}rrr}\toprule',
                r'Phương pháp & Ca & MAE (m) & Hit$_{100}$ (\%) & Recall@5 (\%)\\\midrule']
        for i,name in enumerate(METHODS):
            for j,case in enumerate(CASES):
                r=next(r for r in rows if (r['method'],r['k'],r['case_id'])==(name,k,case))
                tex.append(f"{LABELS[name] if j==0 else ''} & {case} & {r['audit_min_mae_m']:.1f} & {100*r['audit_max_hit100']:.1f} & {100*r['poi_recall']:.1f}"+r'\\')
            if i<len(METHODS)-1:
                tex.append(r'\midrule')
        tex += [r'\bottomrule\end{tabularx}',r'\end{table}']
    (path.parent/'results_tables.tex').write_text('\n'.join(tex)+'\n')
    return audit


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--results',type=Path,default=ROOT/'artifacts/benchmarks/lane_comparison/results.json')
    summarize(parser.parse_args().results)
