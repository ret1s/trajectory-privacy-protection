"""Export checked pilot tables directly to the canonical LaTeX thesis.

Exact lookup tables are used instead of a leaderboard: different contracts,
small sample sizes and several non-interchangeable metrics prohibit ranking.
"""
import json
from pathlib import Path

from experiments.verify_report_demo import DEFAULT, verify

LABELS = {
    "unprotected": "Không bảo vệ", "uniform_dummy": "Dummy đều",
    "dls_graph_adaptation": "DLS (thích nghi)", "rem_anchor_only": "Chỉ neo REM",
    "transprotect_adaptation": "TransProtect (thích nghi)",
    "anotherme_adaptation": "AnotherMe (ngoại tuyến)",
    "semantic_correlation_local_adaptation": "Semantic (thích nghi)",
    "geo_i_anchored_dummy": "Neo + dummy hình học",
    "geo_i_anchored_dummy_road": "Neo + dummy theo đường",
}


def number(v, d=1):
    return "--" if v is None else f"{v:.{d}f}"


def percent(v):
    return "--" if v is None else f"{100 * v:.1f}"


def main():
    check = verify()
    data = json.loads(DEFAULT.read_text())
    rows = {(s["scenario"], s["method"], s["k"]): s for s in data["summary"]}
    text = ["% Generated by experiments.export_report_demo; do not hand-edit numbers.",
            "% Source SHA-256: " + check["artifact_sha256"],
            r"\subsection{Quy mô và trạng thái thực thi}",
            f"Bộ kiểm thử gồm {check['records']} đoạn thuộc 6 xe mô phỏng (2 xe cho mỗi hạt giống), "
            f"tạo {check['rows']} tổ hợp đoạn--cấu hình. Có {check['status']['ok']} đầu ra hợp lệ, "
            f"{check['status']['not_applicable']} trường hợp không áp dụng và {check['status']['failed']} lỗi thực thi. "
            "Cả 24 trường hợp không áp dụng là AnotherMe trên S1/S2. Hai lỗi còn lại là cùng một đoạn S3 "
            "tại hai giá trị $K$, được bộ phân loại tốc độ của AnotherMe gán sang xe đạp, "
            "không tương thích với đồ thị chỉ dành cho xe chở khách. Không thay đầu ra lỗi bằng một tuyến giả tự dựng.",
            "Có 417 POI node đủ điều kiện và 9 POI bị loại vì khoảng cách truy cập vượt 250 m. "
            "Các truy vấn trong mỗi hạt giống dùng cùng loại POI; bộ thử chưa quét đủ mọi loại dịch vụ.",
            r"\subsection{Sai số suy luận và chất lượng ứng dụng}",
            "Các bảng dưới dùng $K=3$, cùng 6 đoạn cho mỗi kịch bản. MAE và độ lệch chuẩn (SD) tính theo đoạn, "
            "đơn vị mét; Hit và Recall được biểu diễn bằng phần trăm. MAE lớn hơn và Hit thấp hơn chỉ phản ánh "
            "đối thủ đã chọn trên bộ thử này. Recall là chất lượng giao được; phương pháp lỗi chịu điểm 0 "
            "khi truy vấn có đáp án. Dấu -- chỉ mục không áp dụng, không phải số 0."]
    for scenario in ("S1", "S2", "S3"):
        text += [r"\begin{table}[H]\centering\small",
                 r"\setlength{\tabcolsep}{4pt}",
                 "\\caption{" + scenario + ": kết quả với $K=3$; bản thích nghi, không phải xếp hạng SOTA.}",
                 r"\begin{tabular}{p{5.0cm}rrrrr}\toprule",
                 r"Phương pháp & MAE & SD & Hit (\%) & Recall (\%) & Số đoạn\\\midrule"]
        for method, label in LABELS.items():
            s = rows[scenario, method, 3]
            text.append(" & ".join([label, number(s["location_mae_m"]), number(s["location_mae_m_sd"]),
                                   percent(s["location_hit_100m"]), percent(s["poi_delivered_recall_at_k"]),
                                   ("--" if s["not_applicable"] == s["attempted"]
                                    else f"{s['completed']}/{s['attempted']}")]) + r"\\")
        text += [r"\bottomrule\end{tabular}\end{table}"]
        if scenario == "S1":
            text += ["Ở S1, chỉ có một lần quan sát nên chưa thể kiểm tra tích luỹ thông tin hay tương quan chuỗi. "
                     "Recall cao ở một mẫu ít sự kiện không chứng minh chất lượng ổn định suốt hành trình. "
                     "Đối chứng không bảo vệ vẫn có sai số so với FCD vì đầu vào được chiếu tới nút gần nhất."]
        elif scenario == "S2":
            d = rows["S2", "dls_graph_adaptation", 3]
            text += [f"Ở S2, DLS có MAE {number(d['location_mae_m'])} m nhưng Hit trong 100 m đạt "
                     f"{percent(d['location_hit_100m'])}\\%. Hai con số cho thấy chỉ báo cáo sai số trung bình "
                     "có thể che khuất nhiều lần đoán đúng xen với một số sai số lớn. Tập chứa thật còn một điểm "
                     "đứng yên qua các lần gửi, tạo tín hiệu cho đối thủ liên tục. Entropy của từng tập không đủ "
                     "để suy ra bảo vệ chuỗi điểm dừng."]
        else:
            g, r = rows["S3", "geo_i_anchored_dummy", 3], rows["S3", "geo_i_anchored_dummy_road", 3]
            text += [f"Ở S3, bản hình học có Recall@5 {percent(g['poi_delivered_recall_at_k'])}\\%, "
                     f"còn bản ràng buộc đường đạt {percent(r['poi_delivered_recall_at_k'])}\\%. "
                     "Sai số suy luận lớn hơn của bản theo đường đi kèm mất chất lượng dịch vụ; không thể dùng "
                     "nó làm chứng cứ vượt trội nếu chưa so tại cùng chất lượng và chi phí. AnotherMe chỉ có "
                     "5/6 đoạn hoàn tất; MAE tính trên đoạn hoàn tất, Recall giao được vẫn tính cả lượt lỗi."]
    text += [r"\subsection{Ràng buộc đường và chi phí: phân tích thành phần}",
             "Bảng sau chỉ so ba cấu hình của cơ chế neo trên S3. Tỷ lệ chuyển tiếp hợp lệ tính trên các "
             "ID luồng ổn định và đồ thị nút giao, không áp dụng cho tập ứng viên không liên kết. "
             "Mỗi hàng có 6 đoạn; thời gian là bình quân sinh đầu ra trên máy macOS arm64, "
             "Python 3.11, không phải p95 trên thiết bị người dùng.",
             r"\begin{table}[H]\centering\small\setlength{\tabcolsep}{4pt}",
             r"\caption{S3: ràng buộc chuyển tiếp và chi phí của các biến thể neo.}",
             r"\begin{tabular}{p{4.3cm}rrrrr}\toprule",
             r"Cấu hình & $K$ & Hợp lệ (\%) & Recall (\%) & ms/sự kiện & Byte/sự kiện\\\midrule"]
    for k in (3, 5):
        for method in ("rem_anchor_only", "geo_i_anchored_dummy", "geo_i_anchored_dummy_road"):
            s = rows["S3", method, k]
            text.append(" & ".join([LABELS[method], str(k), percent(s["directed_track_validity"]),
                                   percent(s["poi_delivered_recall_at_k"]), number(s["amortized_generation_ms"], 3),
                                   number(s["payload_json_bytes_per_request"], 0)]) + r"\\")
    text += [r"\bottomrule\end{tabular}\end{table}",
             "Bản theo đường đạt 100\\% chuyển tiếp hợp lệ theo phép kiểm tra đã định nghĩa. Tuy nhiên, "
             "việc chiếu tọa độ SUMO sang nút giao có thể làm mất thông tin tiến độ trên cạnh: ngay cả chuỗi "
             "không bảo vệ cũng không luôn vượt qua kiểm tra thời gian giữa các nút. Vì vậy tỷ lệ này "
             "đánh giá biểu diễn công bố, không kết luận quỹ đạo thật do SUMO sinh là bất hợp pháp. "
             "Đây là lý do cần chuyển sang trạng thái cạnh và tiến độ dọc cạnh trước khi xác nhận đủ ràng buộc đô thị.",
             "Các cấu hình dùng hạt giống được phân tách theo tên phương pháp, không dùng chung hoàn toàn "
             "các lần rút ngẫu nhiên. Với mẫu nhỏ, khác biệt giữa hai biến thể còn chịu nhiễu lấy mẫu; "
             "bảng này là phân tích thăm dò, chưa phải ước lượng tác động nhân quả của một thành phần.",
             r"\subsection{Kiểm tra tính nhân quả và ranh giới dữ liệu}",
             f"Có {check['prefix_checks']} phép kiểm tra tiền tố với đoạn nhiều sự kiện: "
             f"{check['prefix_pass']} phép vượt qua ở các cấu hình nhân quả; 6 phép còn lại thuộc AnotherMe "
             "và thay đổi đầu ra tiền tố khi bổ sung phần còn lại của hành trình. Kết quả phù hợp với việc "
             "tách AnotherMe thành tham chiếu ngoại tuyến. S1 không có đủ chuỗi để thực hiện kiểm tra này.",
             f"Bộ kiểm chứng tính lại sai số cho {check['evaluated_events']} sự kiện và đối chiếu "
             f"{check['summary_rows']} hàng tổng hợp với dữ liệu thành phần. Kiểm thử riêng xác nhận "
             "hàm xử lý từng điểm và bản xử lý cả đoạn của cơ chế đề xuất cho đầu ra giống nhau khi "
             "khởi tạo cùng trạng thái ngẫu nhiên. Giao diện công bố không chứa tọa độ thật gắn nhãn, "
             "neo nội bộ hay hạt giống của cơ chế; các dữ liệu này chỉ nằm ở phía đánh giá."]
    target = DEFAULT.parent / "results_tables.tex"
    target.write_text("\n\n".join(text) + "\n")
    print(target)


if __name__ == "__main__":
    main()
