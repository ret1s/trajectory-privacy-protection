"""Read verified results into the preparation guide; never rerun an experiment."""
from pathlib import Path
import hashlib
import json

from report_case_labels import display_case

OUT = Path(__file__).resolve().parent
ROOT = OUT.parents[2]
BASE = ROOT / 'artifacts/benchmarks/active_scope_ac_v2'


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def pct(v):
    return f'{100*v:.2f}'.replace('.', ',') + r'\%'


def number(v, digits=1):
    return f'{v:.{digits}f}'.replace('.', ',')


def table(headers, rows, widths):
    cols = '@{}' + ''.join(f'P{{{w}cm}}' for w in widths) + '@{}'
    return ('\\begingroup\\small\n\\begin{longtable}{' + cols + '}\n\\toprule\n'
            + ' & '.join(r'\textbf{' + s + '}' for s in headers) + r'\\\midrule' + '\n'
            + '\n'.join(' & '.join(row) + r'\\[3pt]' for row in rows)
            + '\n\\bottomrule\n\\end{longtable}\n\\endgroup\n')


def main():
    d = json.loads((BASE / 'readout.json').read_text())
    check = json.loads((BASE / 'verification.json').read_text())
    assert check['status'] == 'passed' and check['readout_sha256'] == sha(BASE / 'readout.json')
    for path, digest in d['sources'].items():
        assert sha(ROOT / path) == digest, path
    a = {r['method']: r for r in d['endpoint']['aggregates']}
    h = {(r['method'], r['case_id']): r for r in d['historical']['summaries'] if r['split'] == 'new_groups'}
    controls = ['dls', 'rdg', 'transprotect_markov', 'semantic_poi', 'fake_queries']
    coverage = []
    for sc in ('S1', 'S2', 'S3', 'S9', 'S10'):
        vals = [sum(h[m, sc+'.'+c]['hit100'] for c in 'ABC')/3 for m in controls] if sc in ('S1', 'S2', 'S3') else [a[m][sc]['hit100'] for m in controls]
        proposed = [h[m, sc+'.'+c]['hit100'] for m in ('ours30', 'ours67') for c in 'ABC'] if sc in ('S1', 'S2', 'S3') else [a[m][sc]['hit100'] for m in ('calendar30', 'calendar67')]
        assert all(v == 0 for v in proposed), 'Revisit the guide narrative if measured privacy changes.'
        coverage.append([sc + (' (A/B)' if sc == 'S10' else ''), pct(min(vals))+' - '+pct(max(vals)),
                         r'0\%', '4 nhóm; theo sự kiện' if sc in ('S1', 'S2', 'S3') else '32 nhóm; theo lịch'])
    labels = {'raw': 'Vị trí thật', 'dls': 'DLS', 'rdg': 'RDG', 'transprotect_markov': 'TransProtect*',
              'semantic_poi': 'Semantic*', 'fake_queries': 'Fake-query*', 'anotherme_offline': 'AnotherMe offline',
              'calendar30': 'Đề xuất 30 + lịch', 'calendar67': 'Đề xuất 67 + lịch'}
    endpoint = [[label, pct(a[m]['S9']['hit100'])+' / '+number(a[m]['S9']['mae_m']),
                 pct(a[m]['S10']['hit100'])+' / '+number(a[m]['S10']['mae_m']), pct(a[m]['recall_0.8']),
                 number(a[m]['request_bytes_per_service_event']+a[m]['response_bytes_per_service_event'])]
                for m, label in labels.items()]
    contrasts = [[labels[c['control']], number(100*c['delta'], 2),
                  '['+number(100*c['ci95'][0], 2)+'; '+number(100*c['ci95'][1], 2)+']']
                 for c in d['endpoint']['comparisons'] if c['target'] == 'calendar67' and c['scenario'] == 'S10' and c['metric'] == 'hit100']
    tex = '% Generated by prepare_guide_evidence.py; measured results, not illustrative data.\n'
    tex += '\\newcommand{\\PrivacyEvidence}{\n' + table(['Scenario', 'Năm adapter: Hit100', 'Đề xuất', 'Phạm vi đo'], coverage, [2.0, 5.1, 2.2, 6.4]) + '}\n'
    tex += '\\newcommand{\\EndpointEvidence}{\n' + table(['Phương pháp', 'S9: Hit / MAE', 'S10: Hit / MAE', 'Recall@5', 'Byte'], endpoint, [3.65, 3.55, 3.55, 2.5, 2.2]) + '}\n'
    tex += '\\newcommand{\\EndpointContrasts}{\n' + table(['67 + lịch so với', r'Chênh lệch (điểm \%)', r'Khoảng 95\%'], contrasts, [5.5, 5.1, 5.2]) + '}\n'
    (OUT / 'preparation_evidence.tex').write_text(tex)
    paths = [BASE/'readout.json', BASE/'verification.json', OUT/'report_explained.pdf', OUT/'report_explained.tex',
             OUT/'scenario_guide.json', OUT/'data_samples.json', OUT/'report_case_labels.py', OUT/'method_evidence.json',
             OUT/'score_example.json', ROOT/'evaluation/category_cover.py', ROOT/'benchmark/scheduled_category_client.py',
             ROOT/'evaluation/live_poi.py', Path(__file__)]
    paths += [OUT/'figures'/name for name in ('case_S2_C.pdf', 'case_S9_B.pdf', 'case_S10_B.pdf', 'architecture_current.pdf')]
    evidence = {'prepared_on': '2026-10-02', 'meeting_date': '2026-10-03', 'new_experiments': False,
                'purpose': 'Private preparation companion to the September 26 report as reordered on 2026-10-02 for the 03/10 meeting; same measured results.',
                'sources': {str(f.relative_to(ROOT)): sha(f) for f in paths},
                'source_numerical_checks': check['numerical_checks'],
                'priority_cases': [display_case(c) for c in d['active_priority_cases']],
                'privacy_coverage_rows': coverage, 'endpoint_rows': endpoint, 'contrast_rows': contrasts,
                'aggregation': d['aggregation'], 'cost_policy': d['cost_policy'],
                'illustrative_examples': ['meeting story', 'entropy probabilities', 'five inference errors',
                                          'POI sets and distances', 'greedy-cover candidates', 'public refresh timeline',
                                          'M1/M2 score example from score_example.json']}
    (OUT/'preparation_evidence.json').write_text(json.dumps(evidence, ensure_ascii=False, indent=2)+'\n')
    print('Verified source results; generated 5 scenario rows, 9 comparator rows and 5 paired contrasts.')


if __name__ == '__main__':
    main()
