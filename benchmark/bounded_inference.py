"""Prior-relative average inference, NOT a per-observation posterior bound.

Target must be exogenous / satisfy the declared common-context causal model.
Explicit account/vehicle IDs or a future target generated by public output do
not satisfy this assumption. No default uniform prior or zero error is assumed.
"""
from fractions import Fraction

from benchmark.session_utility_bounds import session_utility_bound
from benchmark.whole_path_chi_square import whole_path_bound


def inference_certificate(gamma=1., selections=64, *, infinite=True,
                          prior_optimal_success_upper=None):
    path=whole_path_bound(gamma,selections,infinite=infinite)
    delta=Fraction(path['exact_rational_utility_shift_upper'])
    kl=Fraction(session_utility_bound(gamma,selections,infinite=infinite)['exact_KL_upper'])
    # ln2 = 2*sum_{k>=0} 1/[(2k+1)*3^(2k+1)] > 56/81 > .69.
    bits=kl/Fraction(69,100)
    result=dict(exact_average_inference_gain_upper=str(delta),
        exact_information_nats_upper=str(kl),exact_information_bits_upper=str(bits),
        average_success_upper=None,prior_bound_assumed=False,
        scope='single ideal-Q session; exogenous private target, common public context; average Bayes reward in [0,1]; NOT pointwise posterior')
    if prior_optimal_success_upper is not None:
        if isinstance(prior_optimal_success_upper,bool):raise ValueError('Rational prior reward bound required')
        prior=Fraction(prior_optimal_success_upper)
        if not 0<=prior<=1:raise ValueError('Prior reward bound in [0,1] required')
        result.update(exact_prior_optimal_success_upper=str(prior),
            average_success_upper=str(min(Fraction(1),prior+delta)),prior_bound_assumed=True)
    return result
